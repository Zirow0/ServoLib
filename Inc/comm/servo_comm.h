#pragma once

#include "servo_protocol.h"
#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

/* ================================================================
 * Callback для відправки байт — надається App шаром.
 * Реалізація: return uart_send(&inst, data, len).
 * ================================================================ */
typedef bool (*servo_comm_send_fn)(const uint8_t *data, size_t len);

/* ================================================================
 * Ініціалізація comm шару.
 * Викликати один раз до uart_init.
 * ================================================================ */
void servo_comm_init(servo_comm_send_fn send_fn);

/* ================================================================
 * ISR callback — підключається як uart_rx_cb_t.
 * Тільки копіює байти у staging буфер, декодування — у main loop.
 * ================================================================ */
void servo_comm_on_rx(const uint8_t *data, size_t len);

/* ================================================================
 * Декодування та диспетчеризація — викликати з main loop.
 * Зчитує staging буфер, декодує frame→packet,
 * зберігає команду для servo_comm_get_command.
 * ================================================================ */
void servo_comm_process_rx(void);

/* ================================================================
 * Отримати останню декодовану команду.
 * Повертає true якщо є нова команда (одноразово).
 * ================================================================ */
bool servo_comm_get_command(servo_command_t *cmd_out);

/* ================================================================
 * Відправити повну телеметрію (struct mode).
 * ================================================================ */
void servo_comm_send_telemetry(const servo_telemetry_t *telem);

/* ================================================================
 * Відправити один параметр телеметрії (param mode).
 * field_idx: TELEM_FIELD_* константи з servo_protocol.h
 * ================================================================ */
void servo_comm_send_param(const servo_telemetry_t *telem, uint8_t field_idx);
