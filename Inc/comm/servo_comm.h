#pragma once

#include "servo_protocol.h"
#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

/* ================================================================
 * Callback для відправки байт — надається App шаром.
 * Реалізація: return uart_send(&inst, data, len).
 * ================================================================ */
typedef bool (*servo_comm_send_fn)(const uint8_t *data, size_t len);

/* ================================================================
 * Ініціалізація comm шару.
 * Викликати один раз до uart_init.
 * ================================================================ */
void servo_comm_init(servo_comm_send_fn send_fn);

/* ================================================================
 * Ініціалізувати pending_cascade_cfg початковими значеннями.
 * Викликати після servo_comm_init з поточною конфігурацією.
 *
 * Без цього виклику param-mode оновлення (один коефіцієнт)
 * повертатимуть структуру з нульовими значеннями в інших полях.
 * ================================================================ */
void servo_comm_seed_cascade_config(const cascade_config_t *cfg);

/* ================================================================
 * ISR callback — підключається як uart_rx_cb_t.
 * Тільки копіює байти у staging буфер, декодування — у main loop.
 * ================================================================ */
bool servo_comm_on_rx(const uint8_t *data, size_t len);

/* ================================================================
 * Декодування та диспетчеризація — викликати з main loop.
 * Зчитує staging буфер, декодує frame→packet,
 * зберігає команду для servo_comm_get_command.
 * ================================================================ */
void servo_comm_process_rx(void);

/* ================================================================
 * Отримати останню декодовану команду.
 * Повертає true якщо є нова команда (одноразово).
 * ================================================================ */
bool servo_comm_get_command(servo_command_t *cmd_out);

/* ================================================================
 * Відправити повну servo_telemetry_t (struct mode).
 * ================================================================ */
void servo_comm_send_telemetry(const servo_telemetry_t *telem);

/* ================================================================
 * Відправити один параметр servo_telemetry_t (param mode).
 * field_idx: TELEM_FIELD_* константи з servo_protocol.h
 * ================================================================ */
void servo_comm_send_param(const servo_telemetry_t *telem, uint8_t field_idx);

/* ================================================================
 * Відправити повну cascade_telemetry_t (struct mode).
 * ================================================================ */
void servo_comm_send_cascade(const cascade_telemetry_t *telem);

/* ================================================================
 * Відправити один параметр cascade_telemetry_t (param mode).
 * field_idx: CASC_TELEM_* константи з servo_protocol.h
 * ================================================================ */
void servo_comm_send_cascade_param(const cascade_telemetry_t *telem, uint8_t field_idx);

/* ================================================================
 * Відправити поточну конфігурацію каскаду хосту (struct mode).
 * ================================================================ */
void servo_comm_send_cascade_config(const cascade_config_t *cfg);

/* ================================================================
 * Отримати нову конфігурацію каскаду від хоста.
 * Повертає true якщо є нова (одноразово).
 * ================================================================ */
bool servo_comm_get_cascade_config(cascade_config_t *cfg_out);
